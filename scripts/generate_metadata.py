#!/usr/bin/env python3
"""Generate live Schwung C metadata from the canonical module descriptor."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "src/module.json"
target = ROOT / "src/ui_metadata.h"
baseline = ROOT / "tests/preset_abi_baseline.json"

def compact(obj):
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=True)

def generate():
    raw = source.read_bytes()
    if len(raw) >= 8192:
        raise SystemExit("module.json exceeds Schwung's 8192-byte loader limit")
    meta = json.loads(raw)
    caps = meta["capabilities"]
    params, levels = caps["chain_params"], caps["ui_hierarchy"]["levels"]
    by_key = {p["key"]: p for p in params}
    if len(by_key) != len(params):
        raise SystemExit("duplicate chain parameter key")
    required = json.loads(baseline.read_text())
    if meta["id"] != required["module_id"]:
        raise SystemExit("module ID is incompatible with existing presets")
    for key, old in required["parameters"].items():
        if key not in by_key:
            raise SystemExit("removed legacy preset key: " + key)
        actual = by_key[key]
        for field, previous in old.items():
            if actual.get(field) != previous:
                raise SystemExit("changed legacy preset ABI: %s.%s" % (key, field))
    pages = {"face": "root", "face_osc1": "osc1", "face_osc2": "osc2", "face_filter": "filter"}
    for key, home in pages.items():
        p = by_key[key]
        if p.get("type") != "canvas" or p.get("as_page") is not True:
            raise SystemExit("invalid native face: " + key)
        if p.get("canvas_script", "canvas.js") != "canvas.js":
            raise SystemExit("invalid canvas script: " + key)
        if len(p.get("extra_keys", [])) > 4:
            raise SystemExit("Schwung supports at most four canvas extras: " + key)
        refs = [x if isinstance(x, str) else x.get("key") for x in levels[home].get("params", [])]
        if key not in refs:
            raise SystemExit("face is not in its dedicated control level: " + key)
        if len(levels[home]["knobs"]) > 8:
            raise SystemExit("more than eight encoder assignments: " + home)
    if levels["root"]["knobs"][:2] != ["lfo_rate", "lfo_depth"]:
        raise SystemExit("root motion controls changed")
    for level in levels.values():
        for key in level.get("knobs", []):
            if key not in by_key:
                raise SystemExit("knob has no chain metadata: " + key)
    content = ("/* Auto-generated by scripts/generate_metadata.py; do not edit. */\n"
               "static const char ui_hierarchy_json[] = " + compact(compact(caps["ui_hierarchy"])) + ";\n"
               "static const char chain_params_json[] = " + compact(compact(params)) + ";\n")
    return content

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("stale ui_metadata.h: run python3 scripts/generate_metadata.py")
        print("PASS: live DSP metadata matches module.json; legacy preset ABI and native pages validated")
    else:
        target.write_text(expected)
        print("Generated", target.relative_to(ROOT))
